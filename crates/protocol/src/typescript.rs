//! 从协议类型生成前端 TypeScript 声明（`apps/desktop/src/protocol.generated.ts`）。

use std::{
    any::TypeId,
    collections::{BTreeMap, HashSet},
};
use ts_rs::{Config, TS, TypeVisitor};

pub(crate) struct Bindings {
    config: Config,
    declarations: BTreeMap<String, String>,
    visited: HashSet<TypeId>,
}

impl Bindings {
    pub(crate) fn config(&self) -> &Config {
        &self.config
    }

    pub(crate) fn add<T: TS + 'static + ?Sized>(&mut self) {
        if !self.visited.insert(TypeId::of::<T>()) {
            return;
        }
        T::visit_generics(self);
        // 具名类型才写 export 声明，其余只递归其依赖。
        if T::output_path().is_some() {
            let name = T::ident(&self.config);
            self.declarations.insert(name, format!("export {}", T::decl(&self.config)));
        }
        T::visit_dependencies(self);
    }
}

impl TypeVisitor for Bindings {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        self.add::<T>();
    }
}

/// 生成前端使用的全部 TypeScript 类型声明和 `RpcContract` 接口；64 位整数按 `number` 导出。
pub fn client_types() -> String {
    let mut bindings = Bindings {
        config: Config::default().with_large_int("number"),
        declarations: BTreeMap::new(),
        visited: HashSet::new(),
    };
    let rpc_contract = crate::rpc::export_rpc_types(&mut bindings);
    bindings.add::<crate::StreamEnvelope>();
    bindings.add::<crate::RpcResponse>();
    let mut output = String::from(
        "// Generated by singularity_protocol; cargo run -p singularity_protocol --features typescript --example export_types\n\n",
    );
    output.push_str(&bindings.declarations.into_values().collect::<Vec<_>>().join("\n\n"));
    output.push_str("\n\n");
    output.push_str(&rpc_contract);
    // ts_rs 在折行的声明上可能留下行尾空格。
    let mut normalized = output.lines().map(str::trim_end).collect::<Vec<_>>().join("\n");
    normalized.push('\n');
    normalized
}
